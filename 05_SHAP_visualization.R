  dt$Feature1 <- clean_feature_names(dt$Feature1)
  dt$Feature2 <- clean_feature_names(dt$Feature2)
  ggplot(dt, aes(Feature1,Feature2,fill=MeanAbsInteraction)) +
    geom_tile(color="white",linewidth=0.8) +
    geom_text(aes(label=sprintf("%.3f",MeanAbsInteraction)),size=4.2,fontface="bold") +
